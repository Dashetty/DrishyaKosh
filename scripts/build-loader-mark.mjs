/**
 * Rebuilds the loading-screen treasure mark from its master PNG.
 *
 *   node scripts/build-loader-mark.mjs [minSpeck=5]
 *
 * Needs ImageMagick (`magick`) and `autotrace` on PATH. Pipeline:
 *   master PNG → crop to the oval (drops the corner sparkle) → 1-bit Otsu
 *   threshold → autotrace (stacked black/white contours) → one evenodd
 *   contour soup, re-grouped by geometry into ring / rays / chest.
 *
 * Outputs (all ink-only, colour comes from CSS):
 *   public/loader/mark-ring.svg    — the rope oval (progress ring, CSS mask)
 *   public/loader/mark-chest.svg   — chest + reel + film + coins (CSS mask)
 *   src/components/loader-mark-rays.ts — the six spark rays, animated inline
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";

const MIN = Number(process.argv[2] ?? 5);
const SRC = "design-src/HighestQuality.png";
// dark-ink bounding box measured on the 2528×1696 master, plus margin; keeps
// the faint bottom-right sparkle out of the trace
const CROP = "1488x1160+519+283";

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "loader-mark-"));
const mono = path.join(tmp, "mono.png");
const traced = path.join(tmp, "trace.svg");

execFileSync("magick", [
  SRC, "-crop", CROP, "+repage", "-colorspace", "gray",
  "-auto-threshold", "OTSU", "-type", "bilevel", "-depth", "1", mono,
]);
execFileSync("autotrace", [
  "-input-format", "png", "-output-format", "svg", "-color-count", "2",
  "-corner-threshold", "100", "-filter-iterations", "4",
  "-error-threshold", "1.0", "-output-file", traced, mono,
]);

const s = fs.readFileSync(traced, "utf8");
// first path is the white page rectangle — drop it
const raw = [...s.matchAll(/<path style="fill:(#[0-9a-f]+);[^"]*" d="([^"]+)"/g)]
  .map((m) => ({ black: m[1] === "#010101", d: m[2] }))
  .slice(1);

const bbox = (sp) => {
  const n = sp.match(/-?\d*\.?\d+/g).map(Number);
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (let i = 0; i < n.length - 1; i += 2) {
    x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]);
    y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]);
  }
  return { x0, y0, x1, y1, w: x1 - x0, h: y1 - y0 };
};
const round1 = (sp) =>
  sp
    .replace(/-?\d*\.?\d+/g, (v) => String(Math.round(parseFloat(v) * 10) / 10))
    .replace(/\s*([MCLz])\s*/g, "$1")
    .replace(/ +/g, " ");

// Every boundary appears exactly once in the stack, so the union of all
// contours under evenodd reproduces the image. Ownership is assigned by
// geometry (never stack order) so each group keeps its own parity.
const contours = raw.flatMap((r) =>
  r.d.split(/(?=M)/).filter((x) => x.trim()).map((sp) => ({ sp, black: r.black, ...bbox(sp) })),
);
const byArea = (a, b) => b.w * b.h - a.w * a.h;
const ringOuter = contours.filter((c) => c.black).sort(byArea)[0];
const ringInner = contours.filter((c) => c !== ringOuter).sort(byArea)[0];
const ecx = (ringOuter.x0 + ringOuter.x1) / 2;
const ecy = (ringOuter.y0 + ringOuter.y1) / 2;
const ea = ringOuter.w / 2;
const eb = ringOuter.h / 2;
const cx = (c) => (c.x0 + c.x1) / 2;
const cy = (c) => (c.y0 + c.y1) / 2;
const radius = (c) => Math.hypot((cx(c) - ecx) / ea, (cy(c) - ecy) / eb);

const rayOuters = contours.filter(
  (c) =>
    c.black && c !== ringOuter && c.w * c.h > 3000 &&
    (cx(c) < 345 || cx(c) > 1150 || (cy(c) < 345 && cx(c) > 880)),
);
const owner = (c) => {
  if (c === ringOuter || c === ringInner) return "ring";
  const ri = rayOuters.indexOf(c);
  if (ri >= 0) return `ray${ri}`;
  for (let i = 0; i < rayOuters.length; i++) {
    const r = rayOuters[i];
    if (c.x0 >= r.x0 - 2 && c.x1 <= r.x1 + 2 && c.y0 >= r.y0 - 2 && c.y1 <= r.y1 + 2) return `ray${i}`;
  }
  return radius(c) >= 0.94 ? "ring" : "chest";
};
const keep = (c) => c === ringOuter || c === ringInner || c.w >= MIN || c.h >= MIN;

const groups = {};
for (const c of contours) if (keep(c)) (groups[owner(c)] ??= []).push(round1(c.sp));

const vb = `${Math.floor(ringOuter.x0)} ${Math.floor(ringOuter.y0)} ${Math.ceil(ringOuter.w)} ${Math.ceil(ringOuter.h)}`;
const [, , vw, vh] = vb.split(" ").map(Number);
const file = (d) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${vw}" height="${vh}"><path fill-rule="evenodd" d="${d}"/></svg>\n`;

fs.mkdirSync("public/loader", { recursive: true });
fs.writeFileSync("public/loader/mark-ring.svg", file(groups.ring.join("")));
fs.writeFileSync("public/loader/mark-chest.svg", file(groups.chest.join("")));

const rays = rayOuters.map((_, i) => groups[`ray${i}`].join(""));
fs.writeFileSync(
  "src/components/loader-mark-rays.ts",
  `// Generated by scripts/build-loader-mark.mjs — do not edit by hand.\n` +
    `export const MARK_VIEWBOX = "${vb}";\n` +
    `export const MARK_ASPECT = ${vw} / ${vh};\n` +
    `export const MARK_RAYS: readonly string[] = ${JSON.stringify(rays, null, 2)};\n`,
);

fs.rmSync(tmp, { recursive: true, force: true });
console.log(
  `viewBox ${vb} | ring ${groups.ring.join("").length}B chest ${groups.chest.join("").length}B rays ${rays.map((r) => r.length).join(",")}`,
);
